export function gearIcon(def: string, slotName: string, name = ''): string {
  if (slotName === 'armor') return 'armor';
  if (slotName === 'trinket') return /amulett|talisman|brosche|kette/i.test(def + name) ? 'amulet' : 'ring';
  if (/speer|hellebarde|spie/i.test(def + name)) return 'spear';
  if (/armbrust|repetier|bolzen/i.test(def + name)) return 'crossbow';
  if (/stab/i.test(def + name)) return 'staff';
  if (/kolben|hammer|axt/i.test(def + name)) return 'mace';
  return 'sword';
}
