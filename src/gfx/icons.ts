const cache = new Map<string, HTMLCanvasElement>();
export function iconCanvas(name: string, scale = 1): HTMLCanvasElement {
  const key = name + '@' + scale;
  const hit = cache.get(key);
  if (hit) return hit;
  let ic = M[name];
  if (!ic && V[name]) { const [base, over] = V[name]; ic = { rows: M[base].rows, pal: { ...M[base].pal, ...over } }; }
  if (!ic) ic = M.star;
  const p = new PB(16, 16);
  p.mask(ic.rows.map((r) => r.padEnd(16, '.').slice(0, 16)), ic.pal);
  p.bevel(0.35, 0.32);
  p.outline('#05060b');
  const [c, ctx] = canvas(16 * scale, 16 * scale);
  p.draw(ctx, 0, 0, scale);
  cache.set(key, c);
  return c;
}

const urlCache = new Map<string, string>();
export function iconUrl(name: string): string {
  let u = urlCache.get(name);
  if (!u) { u = iconCanvas(name, 2).toDataURL(); urlCache.set(name, u); }
  return u;
}

/** Icon im dunkelblauen Slot wie im Referenzbild. */
export function slot(name: string, size = 34): HTMLElement {
  const d = document.createElement('span');
  d.className = 'slot';
  d.style.width = d.style.height = size + 'px';
  const img = document.createElement('img');
  img.src = iconUrl(name);
  img.width = img.height = Math.round(size * 0.72);
  img.alt = '';
  d.appendChild(img);
  return d;
}
export function ico(name: string, size = 18): HTMLImageElement {
  const img = document.createElement('img');
  img.className = 'ico'; img.src = iconUrl(name); img.width = img.height = size; img.alt = '';
  return img;
}

